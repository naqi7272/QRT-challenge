"""## 10. LightGBM as a second model, then ensemble with NN

Trains a per-target LightGBM with the SAME features and SAME GroupKFold splits as the NN, then z-normalizes both models' OOF and test predictions and averages them. The optimal blend weight is found by sweeping on OOF.

**Why ensemble:** NN and GBDT make different mistakes. NN learns smooth representations via gradient descent; GBDT learns rule-like splits. Their errors are partially decorrelated. Averaging reduces variance.

**Tuned LGBM hyperparameters** (vs defaults):
- `lr=0.03` (was 0.05): slower learning, more rounds, better generalization
- `num_leaves=15` (was 31): smaller trees prevent overfit on 2200 samples
- `min_data_in_leaf=80` (was 40): more conservative
- `feature_fraction=0.6` (was 0.8): more random subspace = more diversity per tree
- `lambda_l1=0.5, lambda_l2=2.0`: stronger regularization for small noisy data
- `N_ROUNDS=400` (was 200): compensate for lower learning rate

Tuned version gave LB 0.7471 vs 0.7465 with defaults.
"""

import lightgbm as lgb
from joblib import Parallel, delayed

print("\n" + "="*72)
print("Starting LightGBM ensemble pipeline")
print("="*72)

# Sanity: reuse F_train, F_test, y_panel_filled, mask_panel, day_ids_train
# from the NN section above. Don't refit FeatureBuilder.
assert F_train.shape[0] == y_panel_filled.shape[0], "Feature/label mismatch"

# Load NN predictions we just saved
nn_oof = np.load("nn_oof_logits.npy")
nn_test = np.load("nn_test_logits.npy")
print(f"NN OOF shape: {nn_oof.shape}, NN test shape: {nn_test.shape}")



# Per-target LightGBM — tuned hyperparameters
LGBM_PARAMS = dict(
    objective="regression_l1",     # L1 loss is robust to fat tails in returns
    learning_rate=0.03,            # slower learning, more rounds, better generalization
    num_leaves=15,                 # smaller trees prevent overfit on 2200 samples
    min_data_in_leaf=80,           # more conservative, less overfit
    feature_fraction=0.6,          # more random subspace = more diversity per tree
    bagging_fraction=0.7,
    bagging_freq=3,
    lambda_l1=0.5,                 # light L1 regularization
    lambda_l2=2.0,                 # stronger L2 for small data
    min_gain_to_split=0.0,
    verbose=-1,
)
N_ROUNDS = 200
N_FOLDS = 5

gkf = GroupKFold(n_splits=N_FOLDS)
lgbm_oof = np.zeros_like(nn_oof)
lgbm_test = np.zeros_like(nn_test)

def train_one_target(j, F_tr, y_tr, m_tr, F_va, F_te, params, n_rounds):
    """Train LGBM for one target, return (j, val_pred, test_pred)."""
    m = m_tr[:, j] == 1
    if m.sum() < 50:
        return j, None, None
    weights = np.abs(y_tr[m, j])
    train_set = lgb.Dataset(F_tr[m], y_tr[m, j], weight=weights)
    booster = lgb.train(params, train_set, num_boost_round=n_rounds)
    return j, booster.predict(F_va), booster.predict(F_te)

# Set internal threads to 1 since we're parallelizing across targets externally
LGBM_PARAMS_PARALLEL = {**LGBM_PARAMS, "num_threads": 1, "verbose": -1}

for fold, (tr_idx, va_idx) in enumerate(gkf.split(F_train, groups=day_ids_train)):
    print(f"\n===== LGBM Fold {fold+1}/{N_FOLDS} =====")

    F_tr_fold = F_train[tr_idx]
    F_va_fold = F_train[va_idx]
    y_tr_fold = y_panel_filled[tr_idx]
    m_tr_fold = mask_panel[tr_idx]

    # Train all 100 target models in parallel
    results = Parallel(n_jobs=-1, backend="loky", verbose=1)(
        delayed(train_one_target)(
            j, F_tr_fold, y_tr_fold, m_tr_fold,
            F_va_fold, F_test, LGBM_PARAMS_PARALLEL, N_ROUNDS
        )
        for j in range(N_LIQUID)
    )

    test_preds_fold = np.zeros_like(nn_test)
    for j, val_pred, test_pred in results:
        if val_pred is not None:
            lgbm_oof[va_idx, j] = val_pred
            test_preds_fold[:, j] = test_pred

    lgbm_test += test_preds_fold / N_FOLDS
    print(f"  fold {fold+1} done")

# Save LGBM predictions
