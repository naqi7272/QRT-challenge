np.save("lgbm_test.npy", lgbm_test)

# Compute LGBM standalone OOF score
def weighted_acc(scores, y, mask):
    pred_sign = np.where(scores > 0, 1.0, -1.0)
    true_sign = np.sign(y); true_sign[true_sign == 0] = 1
    correct = (pred_sign == true_sign).astype(np.float32) * mask
    return (correct * np.abs(y)).sum() / ((mask * np.abs(y)).sum() + 1e-8)

print(f"\nNN-only OOF:   {weighted_acc(nn_oof, y_panel_filled, mask_panel):.5f}")
print(f"LGBM-only OOF: {weighted_acc(lgbm_oof, y_panel_filled, mask_panel):.5f}")

# Z-normalize before blending (different models have different scales)
def z_norm(x):
    return (x - x.mean()) / (x.std() + 1e-8)

nn_oof_z = z_norm(nn_oof)
lgbm_oof_z = z_norm(lgbm_oof)
nn_test_z = z_norm(nn_test)
lgbm_test_z = z_norm(lgbm_test)

# Sweep blend weight on OOF
