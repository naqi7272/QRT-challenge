"""## 5. Feature engineering

Applied identically to train and test. Every feature is a deterministic function of the day's illiquid panel plus the static supplementary table. No look-ahead.

Five blocks: raw returns, missingness indicators, sector aggregates across 4 hierarchy levels, cross-sectional stats, PCA factors.
"""

class FeatureBuilder:
    """Stateless on val/test except for a fitted PCA on training illiquid returns.

    Note on the supplementary data: it covers BOTH illiquid and liquid asset
    universes. I verified this by checking that all 100 liquid IDs and all
    100 illiquid IDs appear in the supplementary table. So I can do two
    different things with sectors:
      - aggregate the day's illiquid returns by THEIR sector  (market-side feature)
      - look up the TARGET liquid asset's sector              (target-side feature)
    The second is what makes my model target-aware without having to embed
    a target ID. The interaction between the day's sector returns and the
    target's own sector is what carries the signal.
    """

    def __init__(self, supp, illiquid_ids, liquid_ids, n_pca=16):
        self.supp = supp.set_index("ID_asset")
        self.illiquid_ids = illiquid_ids
        self.liquid_ids = liquid_ids
        self.n_pca = n_pca
        # For each level, map illiquid index -> sector id
        self.illiquid_sectors = {
            lvl: np.array([self.supp.loc[i, f"CLASS_LEVEL_{lvl}"] for i in illiquid_ids])
            for lvl in [1, 2, 3, 4]
        }
        self.liquid_sectors = {
            lvl: np.array([self.supp.loc[i, f"CLASS_LEVEL_{lvl}"] for i in liquid_ids])
            for lvl in [1, 2, 3, 4]
        }
        # All unique sectors per level (across both populations) — used to
        # produce a stable column ordering.
        self.all_sectors = {
            lvl: sorted(set(self.illiquid_sectors[lvl].tolist()
                          + self.liquid_sectors[lvl].tolist()))
            for lvl in [1, 2, 3, 4]
        }
        self.pca = None  # fitted in .fit()

    def _impute_and_indicator(self, X_day):
        """Zero-impute returns + append a NaN-indicator column per asset."""
        nan_mask = np.isnan(X_day).astype(np.float32)
        X_filled = np.where(np.isnan(X_day), 0.0, X_day).astype(np.float32)
        return X_filled, nan_mask

    def _sector_means(self, X_filled, nan_mask):
        """For each sector at each level (using the FULL universe of sectors,
        so column ordering is stable), mean of illiquid returns whose sector
        matches. Computed mask-aware so missing returns don't bias the mean.
        Missing sectors (no illiquid asset belongs there) produce a column of 0s,
        which is harmless after normalization."""
        out = []
        for lvl in [1, 2, 3, 4]:
            sec = self.illiquid_sectors[lvl]
            unique = self.all_sectors[lvl]
            agg = np.zeros((X_filled.shape[0], len(unique)), dtype=np.float32)
            for k, s in enumerate(unique):
                cols = np.where(sec == s)[0]
                if len(cols) == 0:
                    continue
                w = 1.0 - nan_mask[:, cols]
                denom = w.sum(axis=1) + 1e-8
                agg[:, k] = (X_filled[:, cols] * w).sum(axis=1) / denom
            out.append(agg)
        return np.concatenate(out, axis=1)

    def _cross_sectional_stats(self, X_filled, nan_mask):
        """Per-day distribution of illiquid returns: mean, std, skew-ish,
        fraction positive. These give the model a sense of 'market regime'."""
        w = 1.0 - nan_mask
        denom = w.sum(axis=1, keepdims=True) + 1e-8
        mean = (X_filled * w).sum(axis=1, keepdims=True) / denom
        var = (((X_filled - mean) ** 2) * w).sum(axis=1, keepdims=True) / denom
        std = np.sqrt(var + 1e-8)
        skewish = (((X_filled - mean) ** 3) * w).sum(axis=1, keepdims=True) / (denom * std**3 + 1e-8)
        frac_pos = ((X_filled > 0) * w).sum(axis=1, keepdims=True) / denom
        return np.concatenate([mean, std, skewish, frac_pos], axis=1).astype(np.float32)

    def fit(self, X_day_train):
        X_filled, _ = self._impute_and_indicator(X_day_train)
        self.pca = PCA(n_components=self.n_pca, random_state=SEED).fit(X_filled)

    def transform(self, X_day):
        X_filled, nan_mask = self._impute_and_indicator(X_day)
        feats = [
            X_filled,                                  # 100
            nan_mask,                                  # 100  (missingness indicators)
            self._sector_means(X_filled, nan_mask),    # ~ (10 + 22 + 49 + 77) = ~158
            self._cross_sectional_stats(X_filled, nan_mask),  # 4
            self.pca.transform(X_filled).astype(np.float32),  # n_pca
        ]
        return np.concatenate(feats, axis=1).astype(np.float32)

