"""## 6. Model — small MLP with multi-output head

One forward pass produces 100 logits (one per liquid target). The hidden layers learn a shared representation; the output layer specializes per target. Much more sample-efficient than 100 separate per-target models.
"""

class MLP(nn.Module):
    def __init__(self, in_dim, hidden_dims, out_dim, dropout=0.3):
        super().__init__()
        layers = []
        prev = in_dim
        for h in hidden_dims:
            layers += [nn.Linear(prev, h), nn.GELU(),
                       nn.LayerNorm(h), nn.Dropout(dropout)]
            prev = h
        layers += [nn.Linear(prev, out_dim)]
        self.net = nn.Sequential(*layers)

    def forward(self, x):
        return self.net(x)  # logits, shape [B, N_LIQUID]

"""## 7. Loss function — weighted BCE on sign, masked

This is the single most important design choice. The metric is weighted accuracy with weight = |y|, so I train with weighted BCE with weight = |y| × mask. Same shape as the eval function.

Comparison from my iterations:
- v1 used MSE on returns: OOF 0.674, LB 0.675
- v2 switched to this BCE: OOF 0.731, LB 0.738

+57 bps on LB from just changing the loss function. Direct evidence that matching loss to metric matters.
"""

def weighted_masked_bce(logits, y_true, mask, smoothing=0.02):
    """y_true: actual returns (sign + magnitude).
       mask:   1 where y is observed, else 0.
       weight: |y_true| — this aligns optimization with the eval metric.
    """
    target = (y_true > 0).float()
    target = target * (1 - smoothing) + 0.5 * smoothing   # label smoothing
    weight = mask * y_true.abs()
    bce = nn.functional.binary_cross_entropy_with_logits(
        logits, target, reduction="none"
    )
    return (bce * weight).sum() / (weight.sum() + 1e-8)


def weighted_accuracy(logits, y_true, mask):
    """Competition metric — exactly as defined in the spec."""
    pred_sign = torch.sign(logits)         # logits>0 → +1, <0 → -1
    pred_sign[pred_sign == 0] = 1
    true_sign = torch.sign(y_true)
    correct = (pred_sign == true_sign).float() * mask
    weight = mask * y_true.abs()
    return (correct * y_true.abs()).sum() / (weight.sum() + 1e-8)

