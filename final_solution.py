for w in np.linspace(0.0, 1.0, 21):
    blended = w * nn_oof_z + (1 - w) * lgbm_oof_z
    score = weighted_acc(blended, y_panel_filled, mask_panel)
    print(f"  w_nn={w:.2f}: OOF={score:.5f}")
    if score > best_score:
        best_score, best_w = score, w

print(f"\nBest blend: w_nn={best_w:.2f}, OOF={best_score:.5f}")

# Build submission with the best blend
final_test_score = best_w * nn_test_z + (1 - best_w) * lgbm_test_z

